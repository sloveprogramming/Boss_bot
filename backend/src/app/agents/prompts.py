    """按候选人投递岗位/分类结果匹配岗位专项评分标准

    匹配策略：position + category 拼接后做子串匹配（岗位名或别名）。
    命中 → 返回专项锚点文本块（声明优先于通用锚点）；未命中 → 空串（走通用锚点）。
    """
    if not position and not category:
        return ""
    text = f"{position} {category}"
    for name, spec in POSITION_STANDARDS.items():
        keys = [name] + spec.get("aliases", [])
        if any(k and k in text for k in keys):
            return (
                f"\n\n【{name} 岗位专项评分标准（依据岗位价值说明书制定，"
                f"与本锚点冲突时以本标准为准）】\n"
                f"技能分锚点：{spec['skill_anchor']}\n"
                f"经验/稳定性锚点：{spec['experience_anchor']}"
            )
    return ""


